-- English becomes the source language (docs/DESIGN.md §1): category names are stored in English,
-- and the web app translates them by id (web/src/i18n). Ids don't change, so nothing else moves.

UPDATE categories SET name = CASE id
    WHEN 'dining'               THEN 'Dining'
    WHEN 'dining.restaurants'   THEN 'Restaurants'
    WHEN 'dining.fast_food'     THEN 'Fast food'
    WHEN 'dining.coffee'        THEN 'Coffee & tea'
    WHEN 'dining.bars'          THEN 'Bars & alcohol'
    WHEN 'dining.other'         THEN 'Other dining'
    WHEN 'groceries'            THEN 'Groceries'
    WHEN 'shopping'             THEN 'Shopping'
    WHEN 'shopping.online'      THEN 'Online shopping'
    WHEN 'shopping.general'     THEN 'General merchandise'
    WHEN 'shopping.clothing'    THEN 'Clothing'
    WHEN 'shopping.electronics' THEN 'Electronics'
    WHEN 'shopping.other'       THEN 'Other shopping'
    WHEN 'transport'            THEN 'Transportation'
    WHEN 'transport.rideshare'  THEN 'Rideshare & taxis'
    WHEN 'transport.gas'        THEN 'Gas'
    WHEN 'transport.parking'    THEN 'Parking & tolls'
    WHEN 'transport.transit'    THEN 'Public transit'
    WHEN 'transport.auto'       THEN 'Car'
    WHEN 'travel'               THEN 'Travel'
    WHEN 'travel.flights'       THEN 'Flights'
    WHEN 'travel.lodging'       THEN 'Lodging'
    WHEN 'travel.other'         THEN 'Other travel'
    WHEN 'housing'              THEN 'Housing'
    WHEN 'housing.rent'         THEN 'Rent'
    WHEN 'housing.mortgage'     THEN 'Mortgage'
    WHEN 'housing.home'         THEN 'Home & repairs'
    WHEN 'bills'                THEN 'Bills'
    WHEN 'bills.utilities'      THEN 'Utilities'
    WHEN 'bills.telecom'        THEN 'Internet & phone'
    WHEN 'bills.insurance'      THEN 'Insurance'
    WHEN 'bills.subscriptions'  THEN 'Subscriptions'
    WHEN 'entertainment'        THEN 'Entertainment'
    WHEN 'health'               THEN 'Health'
    WHEN 'health.medical'       THEN 'Medical'
    WHEN 'health.fitness'       THEN 'Fitness'
    WHEN 'personal'             THEN 'Personal'
    WHEN 'personal.care'        THEN 'Personal care'
    WHEN 'personal.education'   THEN 'Education'
    WHEN 'personal.services'    THEN 'Services'
    WHEN 'gifts'                THEN 'Gifts & donations'
    WHEN 'taxes'                THEN 'Taxes'
    WHEN 'fees'                 THEN 'Interest & fees'
    WHEN 'fees.interest'        THEN 'Interest charges'
    WHEN 'fees.bank'            THEN 'Bank fees'
    WHEN 'other'                THEN 'Other spending'
    WHEN 'other.p2p'            THEN 'Payments to people'
    WHEN 'other.reimbursement'  THEN 'Money paid back'
    WHEN 'other.credits'        THEN 'Cashback & credits'
    WHEN 'other.cash'           THEN 'Cash withdrawals'
    WHEN 'other.uncategorized'  THEN 'Uncategorized'
    WHEN 'income'               THEN 'Income'
    WHEN 'income.salary'        THEN 'Salary'
    WHEN 'income.interest'      THEN 'Interest income'
    WHEN 'income.tax_refund'    THEN 'Tax refunds'
    WHEN 'income.other'         THEN 'Other income'
    WHEN 'transfer'             THEN 'Transfers'
    WHEN 'transfer.card_payment' THEN 'Card payments'
    WHEN 'transfer.internal'    THEN 'Between accounts'
    WHEN 'transfer.loan'        THEN 'Loan transfers'
    WHEN 'transfer.other'       THEN 'Other transfers'
    ELSE name
END;
